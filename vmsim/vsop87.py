def _evaluate(series, tau: float) -> float:
    total = 0.0
    power = 1.0
    for terms in series:
        s = 0.0
        for a, b, c in terms:
            s += a * math.cos(b + c * tau)
        total += s * power
        power *= tau
    return total * 1e-8


def heliocentric(body: str, jde: float) -> tuple[float, float, float]:
    """Heliocentric (longitude rad, latitude rad, radius AU), ecliptic of date."""
    tau = (jde - 2451545.0) / 365250.0
    if body == "earth":
        l, b, r = EARTH_L, EARTH_B, EARTH_R
    elif body == "venus":
        l, b, r = VENUS_L, VENUS_B, VENUS_R
    else:
        raise KeyError(f"no VSOP87 series for {body!r}")
    return (_evaluate(l, tau) % (2 * math.pi), _evaluate(b, tau), _evaluate(r, tau))


def to_fk5(lon_rad: float, lat_rad: float, jde: float) -> tuple[float, float]:
    """Correct VSOP87's dynamical frame to FK5 (Meeus 32.3). ~0.09" in longitude."""
    t = (jde - 2451545.0) / 36525.0
    lp = lon_rad - math.radians(1.397 * t + 0.00031 * t * t)
    dlon = math.radians((-0.09033 + 0.03916 * (math.cos(lp) + math.sin(lp))
                         * math.tan(lat_rad)) / 3600.0)
    dlat = math.radians(0.03916 * (math.cos(lp) - math.sin(lp)) / 3600.0)
    return lon_rad + dlon, lat_rad + dlat


def rectangular(body: str, jde: float, fk5: bool = True):
    """Heliocentric rectangular position, ecliptic of date, AU."""
    lon, lat, r = heliocentric(body, jde)
    if fk5:
        lon, lat = to_fk5(lon, lat, jde)
    cl = math.cos(lat)
    return (r * cl * math.cos(lon), r * cl * math.sin(lon), r * math.sin(lat))
