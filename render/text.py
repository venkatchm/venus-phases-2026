_BITMAPS = {ch: np.array([[c == "#" for c in row] for row in art.split("/")], dtype=bool)
            for ch, art in _GLYPHS.items()}

GLYPH_W, GLYPH_H = 5, 7


def text_width(s: str, scale: int = 1, spacing: int = 1) -> int:
    return len(s) * (GLYPH_W + spacing) * scale


def draw_text(img: np.ndarray, x: int, y: int, s: str,
              color=(1.0, 1.0, 1.0), scale: int = 1, spacing: int = 1,
              shadow: bool = True) -> None:
    """Draw `s` into a float RGB image at top-left (x, y). Modifies in place."""
    if shadow:
        draw_text(img, x + scale, y + scale, s, color=(0.0, 0.0, 0.0),
                  scale=scale, spacing=spacing, shadow=False)
    h, w = img.shape[0], img.shape[1]
    col = np.asarray(color, dtype=np.float32)
    cx = x
    for ch in s.upper():
        bm = _BITMAPS.get(ch)
        if bm is None:
            bm = _BITMAPS["?"]
        for gy in range(GLYPH_H):
            for gx in range(GLYPH_W):
                if not bm[gy, gx]:
                    continue
                px0, py0 = cx + gx * scale, y + gy * scale
                px1, py1 = min(px0 + scale, w), min(py0 + scale, h)
                if px0 >= w or py0 >= h or px1 <= 0 or py1 <= 0:
                    continue
                img[max(py0, 0):py1, max(px0, 0):px1] = col
        cx += (GLYPH_W + spacing) * scale


def draw_marker(img: np.ndarray, x: int, y: int, color=(1.0, 1.0, 1.0),
                size: int = 3) -> None:
    """A small cross, readable against any background."""
    h, w = img.shape[0], img.shape[1]
    col = np.asarray(color, dtype=np.float32)
    for d in range(-size, size + 1):
        for (px, py) in ((x + d, y), (x, y + d)):
            if 0 <= px < w and 0 <= py < h:
                img[py, px] = col
